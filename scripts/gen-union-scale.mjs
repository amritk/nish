#!/usr/bin/env node
/**
 * Write a discriminated union at typescript-go scale: the shape of its AST
 * node data, with as many variants as asked.
 *
 *   node scripts/gen-union-scale.mjs                 tests/cases/union_scale.ts, 200 variants
 *   node scripts/gen-union-scale.mjs --variants N    N variants instead
 *   node scripts/gen-union-scale.mjs --nodes N       build N nodes instead of 4000 (for timing the walk)
 *   node scripts/gen-union-scale.mjs --out FILE      write FILE instead ("-" is stdout)
 *   node scripts/gen-union-scale.mjs --check         exit 1 if the case is not what this writes
 *
 * The program is an `enum Kind` of N members; N classes, each tagged
 * `readonly kind: Kind.X = Kind.X` and carrying 2 to 6 further fields (an
 * `i32`, a `string`, a `Node | null` child, a `Node[]` of children); `type
 * Node` over all of them; a builder that makes a tree of a few thousand nodes
 * from a fixed seed; a `switch (n.kind)` over every variant that reads the
 * variant's own fields; a forEachChild-style walk; and accessors for the two
 * fields many variants share. Its checksum stays below 2^31 at every step, so
 * Node prints what the native binary prints. The case's purpose is the
 * compile time and the IR of a 200-way union (`tests/cases/union_scale.ts`),
 * so the output is deterministic and the generator is the only author: edit
 * this file, never the case.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const args = process.argv.slice(2)
const flag = (option) => {
  const at = args.indexOf(option)
  return at < 0 ? null : args[at + 1]
}
const variants = Number(flag("--variants") ?? 200)
const nodes = Number(flag("--nodes") ?? 4000)
const out = flag("--out") ?? join(root, "tests/cases/union_scale.ts")
if (!Number.isInteger(variants) || variants < 2 || !Number.isInteger(nodes) || nodes < 1) {
  console.error("gen-union-scale: --variants takes an integer of at least 2, --nodes one of at least 1")
  process.exit(2)
}

// Field kinds, in the order a variant's fields cycle through them.
const I32 = 0
const STR = 1
const CHILD = 2
const LIST = 3

/** The fields after the tag of variant `i`: 2 to 6, a fixed mix of kinds. */
const fieldsOf = (i) => {
  const count = 2 + ((i * 7) % 5)
  const fields = []
  // `flags` and `name` are the fields many variants share, as typescript-go's
  // node data shares `Flags` and `Name()`: an accessor switches over them.
  if (i % 4 === 0) {
    fields.push({ name: "flags", kind: I32 })
  }
  if (i % 3 === 0) {
    fields.push({ name: "name", kind: STR })
  }
  for (let j = 0; fields.length < count; j++) {
    const kind = (i * 3 + j) % 4
    const prefix = ["v", "s", "c", "cs"][kind]
    fields.push({ name: `${prefix}${j}`, kind })
  }
  // Laid out with no padding: one `i32` beside the tag fills its word, then
  // the pointers, then the other `i32`s.
  const ints = fields.filter((f) => f.kind === I32)
  const refs = fields.filter((f) => f.kind !== I32)
  return [...ints.slice(0, 1), ...refs, ...ints.slice(1)]
}

const typeOf = (kind) => ["i32", "string", "Node | null", "Node[]"][kind]

const lines = []
const emit = (s = "") => lines.push(s)
const name = (i) => `N${i}`
const tag = (i) => `K${i}`
const all = Array.from({ length: variants }, (_, i) => ({ i, fields: fieldsOf(i) }))

emit("// GENERATED by scripts/gen-union-scale.mjs: edit the generator, never this file.")
emit(`// A discriminated union of ${variants} variants shaped like typescript-go's node`)
emit("// data: each class tagged by its first field, with 2 to 6 fields of scalars,")
emit("// strings, children and lists of children; a tree built from a fixed seed; a")
emit("// `switch (n.kind)` over every variant that reads its own fields; a")
emit("// forEachChild-style walk; and accessors for the fields many variants share.")
emit("enum Kind {")
for (const { i } of all) {
  emit(`  ${tag(i)},`)
}
emit("}")
emit()
for (const { i, fields } of all) {
  emit(`class ${name(i)} {`)
  emit(`  readonly kind: Kind.${tag(i)} = Kind.${tag(i)};`)
  for (const f of fields) {
    emit(`  ${f.name}: ${typeOf(f.kind)};`)
  }
  emit(`  constructor(${fields.map((f) => `${f.name}: ${typeOf(f.kind)}`).join(", ")}) {`)
  for (const f of fields) {
    emit(`    this.${f.name} = ${f.name};`)
  }
  emit("  }")
  emit("}")
  emit()
}
emit("type Node =")
// One variant a line, the `|` trailing: the parser takes no leading `|`.
for (const { i } of all) {
  emit(`  ${name(i)}${i === variants - 1 ? ";" : " |"}`)
}
emit()

// The builder: a linear congruential seed and a budget of nodes left.
emit("class Builder {")
emit("  left: i32;")
emit("  seed: i32 = 7;")
emit("  constructor(left: i32) {")
emit("    this.left = left;")
emit("  }")
emit()
emit("  next(): i32 {")
// A full-period generator mod 2^16 (a - 1 divisible by 4, c odd) whose low
// bits are dropped, because they cycle with a short period.
emit("    this.seed = (this.seed * 1105 + 12345) % 65536;")
emit("    return this.seed >> 4;")
emit("  }")
emit("}")
emit()
emit("const child = (b: Builder, depth: i32): Node | null =>")
emit("  depth <= 0 || b.left <= 0 ? null : build(b, depth - 1);")
emit()
emit("const children = (b: Builder, depth: i32): Node[] => {")
emit("  const out: Node[] = [];")
emit("  if (depth > 0) {")
emit("    const n = b.next() % 4;")
emit("    for (let i = 0; i < n && b.left > 0; i++) {")
emit("      out.push(build(b, depth - 1));")
emit("    }")
emit("  }")
emit("  return out;")
emit("};")
emit()
const arg = (f) => {
  switch (f.kind) {
    case I32:
      return "b.next()"
    case STR:
      // biome-ignore lint/suspicious/noTemplateCurlyInString: Nish source text; the template is the program's
      return "`s${b.next() % 100}`"
    case CHILD:
      return "child(b, depth)"
    default:
      return "children(b, depth)"
  }
}
emit("const build = (b: Builder, depth: i32): Node => {")
emit("  b.left -= 1;")
emit(`  switch (b.next() % ${variants}) {`)
for (const { i, fields } of all) {
  emit(i === variants - 1 ? "    default:" : `    case ${i}:`)
  emit(`      return new ${name(i)}(${fields.map(arg).join(", ")});`)
}
emit("  }")
emit("};")
emit()

// The switch over every variant, reading the variant's own scalars.
const scalar = (f) => (f.kind === I32 ? `n.${f.name}` : `n.${f.name}.length`)
emit("const score = (n: Node): i32 => {")
emit("  switch (n.kind) {")
for (const { i, fields } of all) {
  const terms = fields.filter((f) => f.kind === I32 || f.kind === STR).map(scalar)
  emit(`    case Kind.${tag(i)}:`)
  emit(`      return ${[String(i), ...terms].join(" + ")};`)
}
emit("  }")
emit("};")
emit()

// forEachChild: every child field and every list, per variant.
emit("class Walk {")
emit("  count: i32 = 0;")
emit("  sum: i32 = 0;")
emit("}")
emit()
emit("const visit = (n: Node, w: Walk): void => {")
emit("  w.count += 1;")
emit("  w.sum = (w.sum * 31 + score(n)) % 1000003;")
emit("  forEachChild(n, w);")
emit("};")
emit()
emit("const forEachChild = (n: Node, w: Walk): void => {")
emit("  switch (n.kind) {")
for (const { i, fields } of all) {
  const kids = fields.filter((f) => f.kind === CHILD || f.kind === LIST)
  emit(`    case Kind.${tag(i)}: {`)
  for (const f of kids) {
    if (f.kind === CHILD) {
      emit(`      const ${f.name} = n.${f.name};`)
      emit(`      if (${f.name} !== null) {`)
      emit(`        visit(${f.name}, w);`)
      emit("      }")
    } else {
      emit(`      for (const c of n.${f.name}) {`)
      emit("        visit(c, w);")
      emit("      }")
    }
  }
  emit("      break;")
  emit("    }")
}
emit("  }")
emit("};")
emit()

// Accessors over the fields many variants share; every other variant answers
// the default, as typescript-go's `Name()` answers nil.
const accessor = (fn, field, type, none) => {
  emit(`const ${fn} = (n: Node): ${type} => {`)
  emit("  switch (n.kind) {")
  for (const { i, fields } of all) {
    if (fields.some((f) => f.name === field)) {
      emit(`    case Kind.${tag(i)}:`)
      emit(`      return n.${field};`)
    }
  }
  emit("    default:")
  emit(`      return ${none};`)
  emit("  }")
  emit("};")
  emit()
}
accessor("flagsOf", "flags", "i32", "0")
accessor("nameOf", "name", "string", '""')

emit("class Tally {")
emit("  flags: i32 = 0;")
emit("  names: i32 = 0;")
emit("}")
emit()
emit("const tally = (n: Node, t: Tally): void => {")
emit("  t.flags = (t.flags + flagsOf(n)) % 1000003;")
emit("  t.names += nameOf(n).length;")
emit("  switch (n.kind) {")
for (const { i, fields } of all) {
  const kids = fields.filter((f) => f.kind === CHILD || f.kind === LIST)
  if (kids.length === 0) {
    continue
  }
  emit(`    case Kind.${tag(i)}: {`)
  for (const f of kids) {
    if (f.kind === CHILD) {
      emit(`      const ${f.name} = n.${f.name};`)
      emit(`      if (${f.name} !== null) {`)
      emit(`        tally(${f.name}, t);`)
      emit("      }")
    } else {
      emit(`      for (const c of n.${f.name}) {`)
      emit("        tally(c, t);")
      emit("      }")
    }
  }
  emit("      break;")
  emit("    }")
}
emit("    default:")
emit("      break;")
emit("  }")
emit("};")
emit()
emit("export const main = (): void => {")
emit(`  const b = new Builder(${nodes});`)
emit("  const roots: Node[] = [];")
emit("  while (b.left > 0) {")
emit("    roots.push(build(b, 8));")
emit("  }")
emit("  const w = new Walk();")
emit("  const t = new Tally();")
emit("  for (const r of roots) {")
emit("    visit(r, w);")
emit("    tally(r, t);")
emit("  }")
// biome-ignore lint/suspicious/noTemplateCurlyInString: Nish source text; the template is the program's
emit("  console.log(`roots ${roots.length} nodes ${w.count} checksum ${w.sum}`);")
// biome-ignore lint/suspicious/noTemplateCurlyInString: Nish source text; the template is the program's
emit("  console.log(`flags ${t.flags} names ${t.names}`);")
emit("};")

const text = `${lines.join("\n")}\n`
if (args.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error(`gen-union-scale: ${out} is not what the generator writes; rerun it`)
    process.exit(1)
  }
} else if (out === "-") {
  process.stdout.write(text)
} else {
  writeFileSync(out, text)
}
