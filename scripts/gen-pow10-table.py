#!/usr/bin/env python3
"""Regenerate the power-of-ten table `runtime/runtime.c` uses for Zmij.

    python3 scripts/gen-pow10-table.py

Prints the C to stdout; paste it over the `NISH_POW10_SIG` definition. The
point of having this in the tree is that the ~10 KB of constants in the
runtime are *derived*, with exact integer arithmetic, rather than transcribed
from somewhere -- so a reader can check them rather than trust them. See
docs/wp15-performance.md section 7a.

Each row is the 128-bit significand of 10^k, normalised so its top bit is set
and rounded *down*, as `{ hi, lo }`: the convention of Zmij's
`pow10_significands` (zmij.c, Copyright (c) 2025 - present, Victor Zverovich,
used under the Boost Software License, Version 1.0; runtime/LICENSE-zmij has
the text and THIRD_PARTY_NOTICES.md the entry). Upstream ships 10^-307 to
10^341 because its fixed-precision paths read further out; the shortest-digits
path, the only one ported, reaches fewer, and the range below is computed from
the same exponent arithmetic `nish_shortest_digits` does rather than copied.
"""

M = (1 << 64) - 1
EXP_OFFSET = 1075  # a double is sig * 2^(raw_exp - 1075)
EXTRA_SHIFT = 6


def dec_exp_of(bin_exp, regular):
    # compute_dec_exp: floor(log10(2^bin_exp)), or of 3/4 of it when irregular.
    # Python's >> floors like the arithmetic shift clang emits for C's int.
    return (bin_exp * 315653 - (0 if regular else 131072)) >> 20


def exp_shift(bin_exp, dec_exp):
    # compute_exp_shift(bin_exp, dec_exp + 1) + extra_shift, as the runtime does it.
    return bin_exp + ((-(dec_exp + 1) * 217707) >> 16) + 1 + EXTRA_SHIFT


def significand(k):
    # floor(10^k * 2^s) for the s that leaves exactly 128 bits.
    if k >= 0:
        p = 10**k
        s = 128 - p.bit_length()
        v = p << s if s >= 0 else p >> -s
    else:
        p = 10**-k
        # 2^(127 + b) / 10^-k with b the bit length of 10^-k lands in [2^127, 2^128).
        v = (1 << (127 + p.bit_length())) // p
    assert v >> 127 == 1, k
    return v


# Every power the shortest path reads: raw_exp 1 (the subnormals and 2^-1022,
# which share its spacing) to 2046, the irregular branch only from 2 up.
reach = set()
for raw_exp in range(1, 2047):
    bin_exp = raw_exp - EXP_OFFSET
    for regular in (True, False) if raw_exp > 1 else (True,):
        d = dec_exp_of(bin_exp, regular)
        shift = exp_shift(bin_exp, d)
        # `bin_sig << shift` must keep a 53-bit significand, and the half-ulp
        # shift `extra_shift + 1 - shift` must be a legal shift count.
        assert 0 <= shift and 53 + shift <= 64, (raw_exp, shift)
        assert 0 <= EXTRA_SHIFT + 1 - shift < 64, (raw_exp, shift)
        reach.add(-d - 1)
lo, hi = min(reach), max(reach)
assert reach == set(range(lo, hi + 1))
assert (lo, hi) == (-293, 323), (lo, hi)

# Spot checks against values a reader can do by hand.
assert significand(0) == 1 << 127
assert significand(-1) == int("cc" * 16, 16)
assert significand(1) == 0xA << 124

print(f"/* Generated by scripts/gen-pow10-table.py; do not hand-edit. 10^{lo} to 10^{hi}. */")
print(f"#define NISH_POW10_MIN ({lo})")
print(f"static const uint64_t NISH_POW10_SIG[{hi - lo + 1}][2] = {{")
for k in range(lo, hi + 1):
    v = significand(k)
    print(f"  {{ 0x{v >> 64:016x}u, 0x{v & M:016x}u }},")
print("};")
