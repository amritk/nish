#!/usr/bin/env node
/**
 * Generate the fixed-base comb table of `std/crypto/p256.ts`.
 *
 *   node scripts/gen-p256-table.mjs           rewrite the table in std/crypto/p256.ts
 *   node scripts/gen-p256-table.mjs --check   exit 1 if the table there differs by a byte
 *
 * The table is the region of `p256.ts` between the `gen-p256-table:begin` and
 * `gen-p256-table:end` lines: `p256BaseTable`, which answers 16 sub-tables of
 * 15 affine points each. Sub-table `c`, entry `j` (1 to 15), is
 *
 *     (j_0 + j_1 2^64 + j_2 2^128 + j_3 2^192) 2^(4c) G
 *
 * where `j_b` is bit `b` of `j`, so a 4-tooth comb whose teeth are 64 bits
 * apart, one sub-table per 4-bit offset of the comb. `p256BaseMult` reads the
 * scalar's bits `i`, `i + 64`, `i + 128` and `i + 192` as one digit and adds
 * the entry it names; 4 rows of 16 such additions, with a doubling between
 * rows, are the whole multiplication. Each entry is X then Y, eight 32-bit
 * limbs each, least significant first, in the Montgomery domain (x 2^256 mod
 * p) that fiat's arithmetic works in: 3,840 limbs, 15 KiB.
 *
 * Computed here with BigInt from SEC 2 §2.4.2's p, b and G, by the textbook
 * affine formulas: the table is public, so nothing here needs to be constant
 * time. The region lives inside `p256.ts` rather than in a module of its own
 * because a file under `std/` is a public `nish/` module, listed as one by the
 * compiler and the release.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const target = path.join(root, "std", "crypto", "p256.ts")

const P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffffn
const B = 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604bn
const G = {
  x: 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296n,
  y: 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5n,
}

/** The comb's shape: teeth 64 bits apart, one sub-table per 4-bit offset. */
const TEETH = 4
const SPACING = 64
const SUBTABLES = 16

const mod = (a) => ((a % P) + P) % P

/** `a^-1 mod p`, by Fermat: p is prime. */
const inverse = (a) => {
  let result = 1n
  let base = mod(a)
  let e = P - 2n
  while (e > 0n) {
    if (e & 1n) {
      result = (result * base) % P
    }
    base = (base * base) % P
    e >>= 1n
  }
  return result
}

/** The affine sum of two points, `null` the identity. */
const add = (p, q) => {
  if (p === null) {
    return q
  }
  if (q === null) {
    return p
  }
  if (p.x === q.x) {
    if (mod(p.y + q.y) === 0n) {
      return null
    }
    const l = mod(3n * p.x * p.x - 3n) * inverse(2n * p.y)
    return finish(p, q, mod(l))
  }
  return finish(p, q, mod(mod(q.y - p.y) * inverse(q.x - p.x)))
}

const finish = (p, q, l) => {
  const x = mod(l * l - p.x - q.x)
  return { x, y: mod(l * (p.x - x) - p.y) }
}

/** `2^n p`. */
const shift = (p, n) => {
  let q = p
  for (let i = 0; i < n; i++) {
    q = add(q, q)
  }
  return q
}

const onCurve = (p) => mod(p.y * p.y) === mod(p.x * p.x * p.x - 3n * p.x + B)

/** The eight 32-bit limbs of `a 2^256 mod p`, least significant first. */
const montgomeryLimbs = (a) => {
  const m = mod(a << 256n)
  const limbs = []
  for (let i = 0n; i < 8n; i++) {
    limbs.push(Number((m >> (32n * i)) & 0xffffffffn))
  }
  return limbs
}

const limbs = []
// The teeth of sub-table c, 2^(4c + 64b) G for b = 0 to 3: sub-table 0's from
// G, each later one's four doublings past the one before.
let teeth = []
for (let b = 0; b < TEETH; b++) {
  teeth.push(shift(G, SPACING * b))
}
for (let c = 0; c < SUBTABLES; c++) {
  if (c > 0) {
    teeth = teeth.map((t) => shift(t, 4))
  }
  for (let j = 1; j < 1 << TEETH; j++) {
    let point = null
    for (let b = 0; b < TEETH; b++) {
      if ((j >> b) & 1) {
        point = add(point, teeth[b])
      }
    }
    if (point === null || !onCurve(point)) {
      throw new Error(`gen-p256-table: sub-table ${c}, entry ${j} is not a point of the curve`)
    }
    limbs.push(...montgomeryLimbs(point.x), ...montgomeryLimbs(point.y))
  }
}

// Biome's layout for an array of numbers at two spaces of indent and 110 columns.
const PER_LINE = 9
const lines = []
for (let i = 0; i < limbs.length; i += PER_LINE) {
  const row = limbs.slice(i, i + PER_LINE).map((l) => `0x${l.toString(16).padStart(8, "0")},`)
  lines.push(`  ${row.join(" ")}`)
}

const BEGIN = "// gen-p256-table:begin"
const END = "// gen-p256-table:end"
const region = [
  `${BEGIN} -- generated by scripts/gen-p256-table.mjs; edit that, not this.`,
  "/**",
  " * The fixed-base comb table `p256BaseMult` reads: sub-table `c` (0 to 15),",
  " * entry `j` (1 to 15) at limb `(15c + j - 1) * 16`, is the affine point",
  " * (j_0 + j_1 2^64 + j_2 2^128 + j_3 2^192) 2^(4c) G, `j_b` bit `b` of `j`, as",
  " * X then Y in the Montgomery domain. Public: a function of G alone.",
  " */",
  "const p256BaseTable = (): u32[] => [",
  ...lines,
  "]",
  END,
].join("\n")

const source = fs.readFileSync(target, "utf8")
const from = source.indexOf(BEGIN)
const to = source.indexOf(END)
if (from < 0 || to < from) {
  console.error(`gen-p256-table: no ${BEGIN} ... ${END} region in ${path.relative(root, target)}`)
  process.exit(1)
}
const next = source.slice(0, from) + region + source.slice(to + END.length)

if (process.argv.includes("--check")) {
  if (next !== source) {
    console.error(
      `gen-p256-table: the table in ${path.relative(root, target)} is not what the generator writes; run node scripts/gen-p256-table.mjs`
    )
    process.exit(1)
  }
  console.log(`gen-p256-table: ${limbs.length} limbs, as generated`)
} else {
  fs.writeFileSync(target, next)
  console.log(`gen-p256-table: wrote ${limbs.length} limbs to ${path.relative(root, target)}`)
}
