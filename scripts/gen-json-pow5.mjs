#!/usr/bin/env node
/**
 * Generate the power-of-five table of `std/json-tokenizer.ts`.
 *
 *   node scripts/gen-json-pow5.mjs           rewrite the table in std/json-tokenizer.ts
 *   node scripts/gen-json-pow5.mjs --check   exit 1 if the table there differs by a byte
 *
 * The table is the region of `json-tokenizer.ts` between the
 * `gen-json-pow5:begin` and `gen-json-pow5:end` lines: `jsonTokPowerOfFive`,
 * which answers the 128-bit truncation of 5^q for q from -342 to 308 as two
 * 64-bit words, high first, so 1,302 words. For q ≥ 0 it is 5^q shifted left
 * or right until its top bit is bit 127, truncated. For q < 0 it is
 * 2^b / 5^-q rounded up, for the b that puts its top bit there; while 5^-q
 * fits in 64 bits (q ≥ -27) that b is z + 127, with z the bit length of 5^-q,
 * and past it the quotient of 2^(2z + 128) is halved down to 128 bits.
 *
 * This is fast_float's `script/table_generation.py`, at commit 0de7a21,
 * written again with BigInt: the table is computed with exact integer
 * arithmetic, so a reader can check it rather than trust a transcription. The
 * region lives inside `json-tokenizer.ts` rather than in a module of its own
 * because a file under `std/` is a public `nish/` module.
 *
 * Adapted from fast_float (https://github.com/fastfloat/fast_float),
 * include/fast_float/decimal_to_binary.h and script/table_generation.py.
 * Copyright 2021 The fast_float authors. Used under the Boost Software License,
 * Version 1.0; see std/LICENSE-fast-float.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const target = path.join(root, "std", "json-tokenizer.ts")

/** `JSON_TOK_SMALLEST_POWER` and `JSON_TOK_LARGEST_POWER`. */
const SMALLEST = -342
const LARGEST = 308

const TOP = 1n << 127n
const LIMIT = 1n << 128n
const WORD = (1n << 64n) - 1n

/** The bit length of a positive BigInt. */
const bits = (n) => n.toString(2).length

const entries = []
for (let q = SMALLEST; q < 0; q++) {
  const p = 5n ** BigInt(-q)
  const z = BigInt(bits(p))
  let c
  if (q >= -27) {
    c = (1n << (z + 127n)) / p + 1n
  } else {
    c = (1n << (2n * z + 128n)) / p + 1n
    while (c >= LIMIT) {
      c /= 2n
    }
  }
  entries.push(c)
}
for (let q = 0; q <= LARGEST; q++) {
  let p = 5n ** BigInt(q)
  while (p < TOP) {
    p *= 2n
  }
  while (p >= LIMIT) {
    p /= 2n
  }
  entries.push(p)
}
for (const [i, c] of entries.entries()) {
  if (c < TOP || c >= LIMIT) {
    throw new Error(`gen-json-pow5: the entry for q = ${i + SMALLEST} does not have its top bit at bit 127`)
  }
}

const words = entries.flatMap((c) => [c >> 64n, c & WORD])
const half = (w) => `0x${w.toString(16).padStart(8, "0")}`
const cases = words.flatMap((w, i) => [
  `    case ${i}:`,
  `      return jsonTokW64(${half(w >> 32n)}, ${half(w & 0xffffffffn)})`,
])

const BEGIN = "// gen-json-pow5:begin"
const END = "// gen-json-pow5:end"
const region = [
  `${BEGIN} -- generated by scripts/gen-json-pow5.mjs; edit that, not this.`,
  "/**",
  ` * The 128-bit truncation of 5^q, high word at \`2 × (q + ${-SMALLEST})\` and low word`,
  ` * after it, for q from ${SMALLEST} to ${LARGEST}: for q ≥ 0, 5^q shifted until its top bit`,
  " * is bit 127; for q < 0, 2^b / 5^-q rounded up, for the b that puts its top",
  " * bit there. Upstream's `power_of_five_128`.",
  " *",
  " * A function over a `switch` rather than an array for `std/crypto/sha512.ts`'s",
  " * reason: a module constant cannot be an array, and LLVM turns a `switch`",
  " * whose every arm is a constant into one read-only table. `index` is computed",
  " * from the exponent, which `numberF64` has bounded.",
  " */",
  "const jsonTokPowerOfFive = (index: i32): u64 => {",
  "  switch (index) {",
  ...cases,
  `    // Unreachable: \`jsonTokEiselLemire\` asks only for 0 to ${words.length - 1}.`,
  "    default:",
  "      return toU64(0)",
  "  }",
  "}",
  END,
].join("\n")

const source = fs.readFileSync(target, "utf8")
const from = source.indexOf(BEGIN)
const to = source.indexOf(END)
if (from < 0 || to < from) {
  console.error(`gen-json-pow5: no ${BEGIN} ... ${END} region in ${path.relative(root, target)}`)
  process.exit(1)
}
const next = source.slice(0, from) + region + source.slice(to + END.length)

if (process.argv.includes("--check")) {
  if (next !== source) {
    console.error(
      `gen-json-pow5: the table in ${path.relative(root, target)} is not what the generator writes; run node scripts/gen-json-pow5.mjs`
    )
    process.exit(1)
  }
  console.log(`gen-json-pow5: ${words.length} words, as generated`)
} else {
  fs.writeFileSync(target, next)
  console.log(`gen-json-pow5: wrote ${words.length} words to ${path.relative(root, target)}`)
}
