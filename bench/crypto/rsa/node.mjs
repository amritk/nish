const a = parseArgs("node.mjs")
if (a.kernel !== "rsa2048-pkcs1-verify" && a.kernel !== "rsa4096-pss-verify") {
  console.error(`node.mjs: no kernel ${a.kernel}`)
  process.exit(2)
}
if (a.size !== SIZE) {
  console.error("node.mjs: the size is 32, the length of the signed messages")
  process.exit(2)
}
const pss = a.kernel === "rsa4096-pss-verify"
const der = Buffer.from(pss ? PSS_KEY : PKCS1_KEY, "hex")
const publicKey = createPublicKey({ key: der, format: "der", type: "pkcs1" })
const key = pss ? { key: publicKey, padding: constants.RSA_PKCS1_PSS_PADDING, saltLength: 32 } : publicKey

const { msg } = inputs(a.kernel, a.size, 0, 0, 0, a.size)
const base = Buffer.from(msg.subarray(0, 4))
const msgs = []
const sigs = (pss ? PSS_SIGS : PKCS1_SIGS).map((hex) => Buffer.from(hex, "hex"))
for (let j = 0; j < sigs.length; j++) {
  const m = Buffer.from(msg)
  tweak(m, 0, base, j)
  msgs.push(m)
}
msgs[TAMPERED][a.size - 1] ^= 1

let sum = fold(FOLD_START, der)
const started = now()
for (let i = 0; i < a.iterations; i++) {
  const j = i % msgs.length
  const ok = verify("sha256", msgs[j], key, sigs[j])
  if (ok !== (j !== TAMPERED)) {
    console.error("node.mjs: a verify gave the wrong answer")
    process.exit(1)
  }
  sum = fold(sum, [ok ? 1 : 0])
}
report(sum, started)
