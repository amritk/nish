/**
 * The extra routes' patterns, kept equal to bench/http-twins/extra-routes.mjs,
 * which check.mjs asks every server.
 */
export const extraRoutes = (): string[] => {
  const statics: string[] = [
    "/catalog/products",
    "/catalog/categories",
    "/catalog/brands",
    "/cart/items",
    "/cart/totals",
    "/checkout/shipping",
    "/checkout/payment",
    "/checkout/review",
    "/orders/recent",
    "/orders/archived",
    "/account/addresses",
    "/account/cards",
    "/account/security",
    "/support/tickets",
    "/support/faq",
    "/stores/nearby",
    "/stores/hours",
    "/promotions/active",
    "/reviews/latest",
    "/wishlist/shared",
  ]
  const params: string[] = [
    "/orders/:orderId",
    "/orders/:orderId/items",
    "/orders/:orderId/items/:itemId",
    "/orders/:orderId/items/:itemId/returns",
    "/products/:productId",
    "/products/:productId/reviews",
    "/products/:productId/reviews/:reviewId",
    "/customers/:customerId/orders",
  ]
  const prefixes: string[] = ["", "/:locale", "/v2", "/v2/:locale"]
  const out: string[] = []
  for (const prefix of prefixes) {
    for (const route of statics) {
      out.push(prefix + route)
    }
    for (const route of params) {
      out.push(prefix + route)
    }
  }
  return out
}

