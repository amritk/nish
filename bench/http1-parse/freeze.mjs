#!/usr/bin/env node
// Writes the frozen copies of the HTTP/1.1 request parser that the parser's
// benchmark and its differential test compare the live one against: the
// parser half of std/net/http1-codec.ts (everything above "The writer") at
// one commit, with every `http1` / `Http1` / `HTTP1_` name given a prefix of
// its own, so that a copy links beside nish/net/http1-codec in one program
// (a module's private helpers share the program's flat symbol namespace).
//
//   node bench/http1-parse/freeze.mjs [<rev>]
//
// <rev> defaults to the commit the copies were frozen from, so running it
// again rewrites the same bytes. Each copy is the same code under another
// prefix: bench/http1-parse/old.ts and old-copy.ts are the benchmark's "old"
// and "old′" (two copies, so their distance is the noise band, code placement
// included), tests/link/net_http1_parse_diff/old.ts the differential test's.
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "..", "..")
/** main when the parser-scan work began. */
const FROZEN = "96a38347484f5fe8dcb64f1298e86e92bdd561c1"
const rev = process.argv[2] ?? FROZEN

const source = execFileSync("git", ["show", `${rev}:std/net/http1-codec.ts`], { cwd: root, encoding: "utf8" })
const cut = source.indexOf("// --- The writer")
if (cut < 0) {
  console.error(`freeze.mjs: ${rev}'s std/net/http1-codec.ts has no "The writer" section`)
  process.exit(2)
}
// The module comment is the live module's; a copy says what it is instead.
const body = source.slice(source.indexOf("\nimport ") + 1, cut).trimEnd()

const COPIES = [
  { file: "bench/http1-parse/old.ts", prefix: "h1a", what: "the benchmark's `old` column" },
  {
    file: "bench/http1-parse/old-copy.ts",
    prefix: "h1b",
    what: "the benchmark's `old′` column, `old` again",
  },
  {
    file: "tests/link/net_http1_parse_diff/old.ts",
    prefix: "h1old",
    what: "the differential test's reference",
  },
]
for (const c of COPIES) {
  const upper = c.prefix.toUpperCase()
  const cap = c.prefix[0].toUpperCase() + c.prefix.slice(1)
  const renamed = body
    .replace(/HTTP1_/g, `${upper}_`)
    .replace(/Http1/g, cap)
    .replace(/http1/g, c.prefix)
  const header =
    "// GENERATED by bench/http1-parse/freeze.mjs from std/net/http1-codec.ts at\n" +
    `// ${rev}: the request parser, every \`http1\` name renamed \`${c.prefix}\`.\n` +
    `// It is ${c.what}. Do not edit; run the script.\n`
  fs.writeFileSync(path.join(root, c.file), `${header}${renamed}\n`)
  console.log(`wrote ${c.file}`)
}
