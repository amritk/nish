/**
 * Writes the x86-64 bcrypt cost-loop kernels into runtime/runtime-bcrypt.c,
 * between its `BEGIN GENERATED` and `END GENERATED` lines; the C around them
 * is written by hand. `--check` writes nothing and fails when the file's
 * generated text is not what this script makes, which `node tests/run.js
 * bcrypt-asm` runs, so a hand edit to the kernels is caught.
 *
 * One function per index style and width, `nish_bcrypt_x86_<style>_<n>(state)`
 * for n from 1 to 6: `state` holds n lanes of 1042 words each (P[18] then
 * S[4][256], a stride of 4168 bytes) with the key already XORed into P, and
 * the function encrypts a zero block and writes its 521 chained outputs over
 * P and the S-boxes in turn, as `bcryptBody` does for each lane.
 *
 * One base register, rdi, reaches every lane, so each S-box and P read is
 * rdi + index × 4 + a constant folded into an add or xor. Five lanes keep
 * their halves in registers and a sixth keeps them on the stack. The sixteen
 * rounds are unrolled, round by round across the lanes. Two styles:
 * - `ah`: byte 0 by movzx from the low byte, byte 1 by bextr, bytes 2 and 3
 *   by one rorx and movzx from al and ah.
 * - `bextr`: byte 3 by a copy and a shift, bytes 2 and 1 by bextr, byte 0 by
 *   movzx; no partial-register reads.
 *
 * Before it returns, a kernel zeroes its frame (the counter and the stack
 * lane's halves) and every caller-saved register it wrote: eax, ecx, edx,
 * esi and r8–r11, which held S-box words, indices and lanes 1 and 2's halves.
 * The callee-saved registers it used for halves get the caller's values back
 * from the stack.
 *
 * Usage: node runtime/gen-bcrypt-x86-64.mjs [--check]
 *
 * Adapted from the multicore-server-challenge submission rust-epoll-WorriedArrow,
 * submissions/rust-epoll-WorriedArrow/build.rs (pull request #152, itself a port
 * of nick-potts's asm_gen.zig in zig-iouring-nick-potts).
 * Copyright (c) 2026 arjaythedev and the challenge contributors.
 * MIT License; see runtime/LICENSE-multicore-server-challenge.
 */
import fs from "node:fs"
import path from "node:path"

const file = path.join(import.meta.dirname, "runtime-bcrypt.c")
const BEGIN = "/* BEGIN GENERATED by runtime/gen-bcrypt-x86-64.mjs: do not edit by hand. */"
const END = "/* END GENERATED */"

const MAX_LANES = 6
const WORDS = 18 + 4 * 256
const STRIDE = WORDS * 4
const ENCRYPTIONS = WORDS / 2
const REG_LANES = 5
const HALVES = [
  ["ebx", "ebp"],
  ["r8d", "r9d"],
  ["r10d", "r11d"],
  ["r12d", "r13d"],
  ["r14d", "r15d"],
]
const LOW = [
  ["bl", "bpl"],
  ["r8b", "r9b"],
  ["r10b", "r11b"],
  ["r12b", "r13b"],
  ["r14b", "r15b"],
]
const SAVED = ["rbx", "rbp", "r12", "r13", "r14", "r15"]

/** The stack offset of stack lane u's half h; offset 0 is the counter. */
const slot = (u, h) => 8 + 8 * (u - REG_LANES) + 4 * h

/** `y ^= P[r] ^ F(x)` for lane u, where x is half `hx` and y the other. */
const halfRound = (o, style, u, hx, r) => {
  const base = u * STRIDE
  const s = base + 72
  const hy = 1 - hx
  if (u < REG_LANES) {
    const x = HALVES[u][hx]
    const y = HALVES[u][hy]
    o.push(`xor ${y}, dword ptr [rdi + ${base + 4 * r}]`)
    if (style === "ah") {
      o.push(`rorx eax, ${x}, 16`, "movzx esi, ah", `mov edx, dword ptr [rdi + rsi*4 + ${s}]`, "movzx esi, al")
    } else {
      o.push(`mov esi, ${x}`, "shr esi, 24", `mov edx, dword ptr [rdi + rsi*4 + ${s}]`, `bextr esi, ${x}, eax`)
    }
    o.push(
      `add edx, dword ptr [rdi + rsi*4 + ${s + 1024}]`,
      `bextr esi, ${x}, ecx`,
      `xor edx, dword ptr [rdi + rsi*4 + ${s + 2048}]`,
      `movzx esi, ${LOW[u][hx]}`,
      `add edx, dword ptr [rdi + rsi*4 + ${s + 3072}]`,
      `xor ${y}, edx`
    )
  } else {
    const x = slot(u, hx)
    o.push(
      `movzx esi, byte ptr [rsp + ${x + 3}]`,
      `mov edx, dword ptr [rdi + rsi*4 + ${s}]`,
      `movzx esi, byte ptr [rsp + ${x + 2}]`,
      `add edx, dword ptr [rdi + rsi*4 + ${s + 1024}]`,
      `movzx esi, byte ptr [rsp + ${x + 1}]`,
      `xor edx, dword ptr [rdi + rsi*4 + ${s + 2048}]`,
      `movzx esi, byte ptr [rsp + ${x}]`,
      `add edx, dword ptr [rdi + rsi*4 + ${s + 3072}]`,
      `xor edx, dword ptr [rdi + ${base + 4 * r}]`,
      `xor dword ptr [rsp + ${slot(u, hy)}], edx`
    )
  }
}

/** The kernel for `n` lanes in `style`, as the lines of its body after the label. */
const kernel = (style, n) => {
  const o = []
  const stackLanes = Math.max(0, n - REG_LANES)
  // The counter and the stack lanes. The kernel calls nothing, so the frame
  // needs no alignment.
  const frame = 8 + 8 * stackLanes
  for (const r of SAVED) {
    o.push(`push ${r}`)
  }
  o.push(`sub rsp, ${frame}`, "mov ecx, 0x0808")
  if (style === "bextr") {
    o.push("mov eax, 0x0810")
  }
  o.push("mov qword ptr [rsp], 0")
  for (let u = 0; u < n; u++) {
    if (u < REG_LANES) {
      o.push(`xor ${HALVES[u][0]}, ${HALVES[u][0]}`, `xor ${HALVES[u][1]}, ${HALVES[u][1]}`)
    } else {
      o.push(`mov qword ptr [rsp + ${slot(u, 0)}], 0`)
    }
  }
  o.push(".p2align 4", "1:")
  for (let u = 0; u < n; u++) {
    if (u < REG_LANES) {
      o.push(`xor ${HALVES[u][0]}, dword ptr [rdi + ${u * STRIDE}]`)
    } else {
      o.push(`mov edx, dword ptr [rdi + ${u * STRIDE}]`, `xor dword ptr [rsp + ${slot(u, 0)}], edx`)
    }
  }
  for (let r = 1; r < 17; r += 2) {
    for (let u = 0; u < n; u++) {
      halfRound(o, style, u, 0, r)
    }
    for (let u = 0; u < n; u++) {
      halfRound(o, style, u, 1, r + 1)
    }
  }
  // The output block (R ^ P[17], L) goes to words 2j and 2j + 1 and is the
  // next input: store it, then swap the halves.
  o.push("mov rsi, qword ptr [rsp]")
  for (let u = 0; u < n; u++) {
    const base = u * STRIDE
    if (u < REG_LANES) {
      const [l, r] = HALVES[u]
      o.push(
        `xor ${r}, dword ptr [rdi + ${base + 68}]`,
        `mov dword ptr [rdi + rsi*8 + ${base}], ${r}`,
        `mov dword ptr [rdi + rsi*8 + ${base + 4}], ${l}`,
        `mov edx, ${l}`,
        `mov ${l}, ${r}`,
        `mov ${r}, edx`
      )
    } else {
      o.push(
        `mov edx, dword ptr [rsp + ${slot(u, 1)}]`,
        `xor edx, dword ptr [rdi + ${base + 68}]`,
        `mov eax, dword ptr [rsp + ${slot(u, 0)}]`,
        `mov dword ptr [rdi + rsi*8 + ${base}], edx`,
        `mov dword ptr [rdi + rsi*8 + ${base + 4}], eax`,
        `mov dword ptr [rsp + ${slot(u, 0)}], edx`,
        `mov dword ptr [rsp + ${slot(u, 1)}], eax`
      )
    }
  }
  // The stack lane's swap used eax.
  if (style === "bextr" && stackLanes > 0) {
    o.push("mov eax, 0x0810")
  }
  o.push("add rsi, 1", "mov qword ptr [rsp], rsi", `cmp rsi, ${ENCRYPTIONS}`, "jb 1b")
  // The wipe: the frame, then the caller-saved registers that held secrets.
  for (let at = 0; at < frame; at += 8) {
    o.push(`mov qword ptr [rsp + ${at}], 0`)
  }
  o.push("xor eax, eax", "xor ecx, ecx", "xor edx, edx", "xor esi, esi")
  for (const r of ["r8d", "r9d", "r10d", "r11d"]) {
    o.push(`xor ${r}, ${r}`)
  }
  o.push(`add rsp, ${frame}`)
  for (const r of [...SAVED].reverse()) {
    o.push(`pop ${r}`)
  }
  o.push("ret")
  return o
}

/** The generated text: one `__asm__` block with every kernel, and their C declarations. */
export const generate = () => {
  const out = [BEGIN, "__asm__(", '    ".text\\n"', '    ".intel_syntax noprefix\\n"']
  const decls = []
  for (const style of ["ah", "bextr"]) {
    for (let n = 1; n <= MAX_LANES; n++) {
      const name = `nish_bcrypt_x86_${style}_${n}`
      decls.push(`void ${name}(uint32_t *state) NISH_BCRYPT_HIDDEN;`)
      out.push(`    NISH_BCRYPT_BEGIN("${name}")`)
      for (const line of kernel(style, n)) {
        out.push(line.endsWith(":") || line.startsWith(".") ? `    "${line}\\n"` : `    "  ${line}\\n"`)
      }
      out.push(`    NISH_BCRYPT_END("${name}")`)
    }
  }
  out.push('    ".att_syntax prefix\\n");', "", ...decls, END)
  return out.join("\n")
}

const text = fs.readFileSync(file, "utf8")
const from = text.indexOf(BEGIN)
const to = text.indexOf(END)
if (from < 0 || to < from) {
  console.error(`${file}: no ${BEGIN} ... ${END} region`)
  process.exit(1)
}
const next = text.slice(0, from) + generate() + text.slice(to + END.length)
if (process.argv.includes("--check")) {
  if (next !== text) {
    console.error(`${file}: the generated kernels differ from what runtime/gen-bcrypt-x86-64.mjs writes; rerun it`)
    process.exit(1)
  }
} else if (next !== text) {
  fs.writeFileSync(file, next)
}
