/**
 * The checked-in successors to the four oracles that die with stage0
 * (WP19 gate G2.4, `docs/wp19-stage0-retirement.md` §2B and §3).
 *
 *   node tests/self/goldens.js                 verify all four against stage1
 *   node tests/self/goldens.js checked         just one of them
 *   node tests/self/goldens.js --update        rewrite the goldens from stage1
 *   node tests/self/goldens.js --seed <nish>   the compiler that builds stage1
 *   node tests/self/goldens.js --verbose --lines 40
 *
 * `checked_oracle.js`, `types_oracle.js`, `diagnostics_oracle.js` and
 * `symbols_oracle.js` each prove stage1 correct by comparing it with stage0.
 * The day stage0's `src/` is deleted they prove nothing, because the thing they compare
 * against is gone. They are green today, which is the whole opportunity: the
 * two implementations agree, so stage1's output *is* the agreed behaviour, and
 * writing it down keeps it past stage0's death.
 *
 * So this tool records the same four outputs as goldens and compares stage1's
 * live output against them. It names neither stage0's `src/` nor `dist/` anywhere, and
 * the only compiler it runs is one it builds out of `src/` — which is why it
 * still works in a tree where stage0 has been deleted. The four oracles keep
 * running beside it for as long as stage0 lives; nothing here replaces them
 * while they can still say something this cannot.
 *
 * **The seed.** Building stage1 takes a compiler, and after retirement that is
 * the last released `nish` (G3). The seed is `--seed`, then `NISH_BOOTSTRAP` —
 * the variable `scripts/bootstrap.sh` reads — then `build/nish`, what
 * `npm run bootstrap` leaves behind; `tests/self/seed.js` resolves it, and the
 * four oracles that outlive stage0 now build their binaries the same way.
 * There is deliberately no fourth answer *here*: a tool that reached for
 * stage0 when it found nothing would be exactly the dependency this gate
 * exists to remove. `tests/run.js` passes today's seed in with `--seed`,
 * because the *suite* still has stage0 and this tool must not.
 *
 * **What each golden holds.**
 *
 *   - `goldens/checked/<module>.txt` — `--emit-checked` for every program of
 *     the corpus, `src/` included, stored **one file per module**: a program
 *     re-dumps every module it imports, so the dump of `std/json.ts` is
 *     written once rather than under each of the programs that load it. A
 *     corpus program's own file opens with its `entry` line, the modules it
 *     loaded in load order, or its `reject` line, the wording it was refused
 *     with. Nothing is measured out: the check still runs every program and
 *     compares every byte it prints, and a module whose dump differs between
 *     two programs is a hard error rather than a silent pick. See
 *     `produceChecked` for why the layout is this one.
 *   - `goldens/types.txt`, `goldens/diagnostics.txt`, `goldens/symbols.txt` —
 *     the stdout of the three driver programs the dying oracles run
 *     (`tests/self/types.ts` and friends), which is the whole of what those
 *     oracles compare.
 *
 * A golden is regenerated by `npm run test:update`, the same command that
 * writes a missing `.ll`, or by `--update` here. Regenerate it from stage1 and
 * never from stage0: stage1 is what survives, and the existing oracles are
 * what say the two agree.
 */
import fs from "node:fs"
import path from "node:path"
import { spawnSync } from "node:child_process"
import { fileURLToPath } from "node:url"
import { checkerArgs, programs, root } from "./corpus.js"
// The seed resolution is shared with the four oracles that survive stage0
// (WP19 G2.3), and `defaultSeedSpec` is where this file's rule lives: three
// answers and no fourth, because a tool that reached for stage0 would be the
// dependency the gate exists to remove.
import { defaultSeedSpec, resolveSeed, spawnSeed } from "./seed.js"

const GOLDENS = path.join(root, "tests", "self", "goldens")
const BUILD = path.join(root, "build", "self", "goldens")

/** Long dump lines are cut to this in a failure report, so a diff stays readable. */
const MAX_LINE = 160

/** The first diagnostic of a compiler's stderr, without its file:line:col prefix. */
const firstLine = (output) => {
  const line = output.trim().split("\n")[0] ?? ""
  return line.replace(/^[^:]*:\d+:\d+: /, "")
}

/**
 * One stage1 program, built out of live sources by the seed. The binaries land
 * under `build/` and are rebuilt on every run: a golden compared against a
 * stale binary is a golden comparing itself with yesterday.
 */
const link = (seed, source, stem) => {
  const out = path.join(BUILD, stem)
  fs.mkdirSync(BUILD, { recursive: true })
  const built = spawnSeed(seed, [path.join(root, source), "--link", out])
  if (built.status !== 0) {
    return { error: `${seed.label} could not build ${source}:\n${built.stderr}` }
  }
  return {
    run: (args) => spawnSync(out, args, { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 }),
  }
}

/**
 * The dump's lines, blanks dropped — `checked_oracle.js`'s normalisation —
 * with `src/branding.ts`'s folded `VERSION` replaced by a placeholder.
 *
 * The checker folds module constants, so the dump records `VERSION`'s value,
 * which is the compiler's version and changes at every release. Pinning it
 * would mean the release pull request — the commit whose whole job is to bump
 * the version — turns this golden red at itself. That the constant is folded
 * at all is still pinned here, by this line's shape and by every other module
 * constant in the corpus; only the digits are let go. `tests/run.js` does the
 * same to the DWARF producer, for the same reason.
 */
const dumpLines = (dump) =>
  dump
    .split("\n")
    .filter((line) => line.length > 0)
    .map((line) => line.replace(/^(const VERSION: string = )"[^"]*"/, '$1"<version>"'))

const header = (what) => [
  `# ${what}`,
  "# Generated from stage1 by `npm run test:update` (or `node tests/self/goldens.js --update`).",
  "# WP19 gate G2.4: the coverage that dies with stage0, written down. Do not edit by hand.",
]

/** The directory under `GOLDENS` that holds the `--emit-checked` goldens, one file per module. */
const CHECKED_DIR = "checked"

/** `src/checker.ts` → `checked/src/checker.ts.txt`: a module's golden sits at its own path. */
const moduleGolden = (module) => `${CHECKED_DIR}/${module}.txt`

/** A body line that carries a source position: `  local 3503:9 owner: ...`. */
const POSITIONED = /^(\s+(?:local|callee|sharedWrite:) )(\d+):(\d+)/

/**
 * A module's dump with every body's line numbers counted from that body's
 * first position, so `  local 3503:9` becomes `  local +0:9` and the next
 * line down `  local +4:14`. A top-level line (`function`, `struct`, `const`)
 * starts a body; the indented lines after it belong to it.
 *
 * The dump prints absolute lines, and an absolute line moves whenever
 * anything above it does: adding one line near the top of `src/checker.ts`
 * rewrote every later `local` and `callee` of the module, so a one-function
 * fix moved a thousand golden lines and two unrelated changes to one file
 * conflicted all the way down. Counted from the body, a line moves only when
 * its own function changes. What is let go is the body's offset in the file;
 * the column, and every position relative to the body's others, are still
 * pinned. `unsafe` records stay absolute: they sit at module level, with no
 * body to count from, and a program that opts out of a check is rare enough
 * that their churn is not what conflicts.
 */
const relativeLines = (lines) => {
  let anchor = null
  return lines.map((line) => {
    if (!line.startsWith(" ")) {
      anchor = null
      return line
    }
    const at = POSITIONED.exec(line)
    if (at === null) {
      return line
    }
    const row = Number(at[2])
    if (anchor === null) {
      anchor = row
    }
    const offset = row - anchor
    return `${at[1]}${offset < 0 ? offset : `+${offset}`}:${at[3]}${line.slice(at[0].length)}`
  })
}

/**
 * `--emit-checked` over the whole corpus, one golden file per module.
 *
 * The layout is set by how the goldens are changed rather than by how they are
 * read. Nearly every pull request that touches `src/`, `std/` or adds a case
 * moves them, so two open pull requests each regenerate them, and the second
 * to land conflicts with the first. With every module in its own file, git
 * merges two changes to two different modules by itself, and only a change to
 * the same module is left to regenerate. Two things in the older single-file
 * layout conflicted whatever two pull requests changed, and are gone: a
 * running count of programs and dump lines in the header, and whole dumps per
 * program, which wrote one change to a `std/` module out again under every
 * case that imported it.
 *
 * Deduplication is a measurement, not an assumption: every module dumps the
 * same text under every program that loads it, whatever its `--number-mode`
 * (1,175 programs over 1,198 distinct modules when this was written), and the
 * generator checks that on every run rather than picking one.
 */
const produceChecked = (seed) => {
  const dumper = link(seed, path.join("src", "dump-checked.ts"), "dump_checked")
  if (dumper.error !== undefined) {
    return { error: dumper.error }
  }

  const entries = new Map()
  const bodies = new Map()
  const bodyOwner = new Map()
  let dumped = 0
  let dumpLineCount = 0

  for (const file of programs()) {
    const named = path.relative(root, file).split(path.sep).join("/")
    const flags = checkerArgs(file)
    const label = flags.length > 0 ? ` ${flags.join(" ")}` : ""
    const result = dumper.run([...flags, named])
    if (result.status !== 0) {
      // A program the checker refuses has no dump, and the reason it gives is
      // a diagnostic wording nothing else here would pin. It belongs in the
      // record for the same reason the dump does.
      entries.set(named, `reject${label}: ${firstLine(result.stderr)}`)
      continue
    }
    const lines = relativeLines(dumpLines(result.stdout))
    dumped++
    dumpLineCount += lines.length
    const order = []
    let module = null
    let body = []
    const close = () => {
      if (module === null) {
        return
      }
      order.push(module)
      const text = body.join("\n")
      const seen = bodies.get(module)
      if (seen === undefined) {
        bodies.set(module, text)
        bodyOwner.set(module, named)
        return
      }
      if (seen !== text) {
        // Deduplication is only sound while a module dumps the same under
        // every program that loads it. It does today; the day it stops, the
        // golden has to grow a dimension rather than quietly pick a winner.
        return `module ${module} dumps differently under ${bodyOwner.get(module)} and ${named}`
      }
      return
    }
    let conflict
    for (const line of lines) {
      const at = /^module (\S+)(?: \(entry\))?$/.exec(line)
      if (at !== null) {
        conflict = close() ?? conflict
        module = at[1]
        body = []
      } else if (module !== null) {
        body.push(line)
      }
    }
    conflict = close() ?? conflict
    if (conflict !== undefined) {
      return { error: conflict }
    }
    entries.set(named, `entry${label}: ${order.join(" ")}`)
  }

  const files = new Map()
  for (const module of [...new Set([...entries.keys(), ...bodies.keys()])].sort()) {
    const text = [
      `# stage1's \`--emit-checked\` of ${module}, each body's lines counted from its first position.`,
      "# Generated by `node tests/self/goldens.js --update` (or `npm run test:update`). Do not edit by hand.",
    ]
    const entry = entries.get(module)
    if (entry !== undefined) {
      text.push(entry)
    }
    const body = bodies.get(module)
    if (body !== undefined && body.length > 0) {
      text.push(body)
    }
    files.set(moduleGolden(module), `${text.join("\n")}\n`)
  }
  return {
    files,
    dir: CHECKED_DIR,
    note: `${dumped} programs, ${dumpLineCount} dump lines, ${bodies.size} distinct modules`,
  }
}

/**
 * One of the three driver programs the dying oracles run. Their stdout is the
 * whole of what those oracles compare — `types_oracle.js` rebuilds it from
 * `dist/types.js` and diffs it line by line — so the stdout is the golden.
 */
const produceDriver = (name, source, args, what) => (seed) => {
  const driver = link(seed, source, name)
  if (driver.error !== undefined) {
    return { error: driver.error }
  }
  const run = driver.run(args)
  if (run.status !== 0) {
    return { error: `${name} exited ${run.status}\n${run.stderr}` }
  }
  const lines = run.stdout.split("\n")
  return {
    files: new Map([[`${name}.txt`, `${header(what).join("\n")}\n${run.stdout}`]]),
    note: `${lines.length - 1} lines`,
  }
}

/**
 * The four goldens, each named for the oracle whose coverage it holds. The
 * `oracle` field is what the summary cites, so that a reader of a failure can
 * find the comparison this file was taken from while it still exists.
 */
const GOLDEN_SET = [
  {
    name: "checked",
    oracle: "checked_oracle.js",
    produce: produceChecked,
  },
  {
    name: "types",
    oracle: "types_oracle.js",
    produce: produceDriver(
      "types",
      path.join("tests", "self", "types.ts"),
      [],
      "`src/types.ts` over the type list `tests/self/types.ts` builds: every LLVM type, alignment, printed name, flag and assignable pair."
    ),
  },
  {
    name: "diagnostics",
    oracle: "diagnostics_oracle.js",
    produce: produceDriver(
      "diagnostics",
      path.join("tests", "self", "diagnostics.ts"),
      [
        path.join("tests", "self", "diagnostics-fixture.txt"),
        path.join("tests", "self", "diagnostics-second.txt"),
      ],
      "`src/diagnostics.ts` over the fixtures: the line/column index, every summary line and excerpt, the `--json` object, the sink's order and its `...and N more` cut."
    ),
  },
  {
    name: "symbols",
    oracle: "symbols_oracle.js",
    produce: produceDriver(
      "symbols",
      path.join("tests", "self", "symbols.ts"),
      [],
      "`src/symbols.ts` over the scope script: what each name resolves to, what it reads as, and where every narrowing stops."
    ),
  },
]

/** The first differences between two texts, bounded, with long lines cut. */
const diff = (want, got, limit) => {
  const a = want.split("\n")
  const b = got.split("\n")
  const out = []
  const cut = (line) => {
    if (line === undefined) {
      return "<end of file>"
    }
    return line.length > MAX_LINE ? `${line.slice(0, MAX_LINE)}...` : line
  }
  let total = 0
  let shown = 0
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] === b[i]) {
      continue
    }
    total++
    if (shown < limit) {
      out.push(`  line ${i + 1}:`, `    golden: ${cut(a[i])}`, `    stage1: ${cut(b[i])}`)
      shown++
    }
  }
  return { total, shown, out }
}

const goldenPath = (file) => path.join(GOLDENS, file)

/** How many failing files show their differing lines without `--verbose`. */
const FILES_SHOWN = 5

/** Every file under `dir` in `GOLDENS`, as the `/`-separated path a golden names it by. */
const filesUnder = (dir) => {
  const at = goldenPath(dir)
  if (!fs.existsSync(at)) {
    return []
  }
  return fs
    .readdirSync(at, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(GOLDENS, path.join(entry.parentPath, entry.name)).split(path.sep).join("/"))
}

/** Removes the directories under `dir` that `--update` left empty, deepest first. */
const removeEmptyDirs = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      removeEmptyDirs(path.join(dir, entry.name))
    }
  }
  if (fs.readdirSync(dir).length === 0) {
    fs.rmdirSync(dir)
  }
}

/**
 * The seed this file's rule allows: `given` (a `--seed` value), then
 * `NISH_BOOTSTRAP`, then `build/nish`, and no fourth answer. Exported because
 * the oracles that outlive stage0 (`lexer-oracle.js`, `parser-oracle.js`,
 * `support-oracle.js`) follow the same rule since R6 took their stage0
 * fallback away, and one spelling of it is enough.
 */
const seedWithoutStage0 = (given) => {
  const spec = given ?? defaultSeedSpec()
  if (spec === null) {
    return {
      error:
        "no seed compiler: pass --seed <nish>, set NISH_BOOTSTRAP, or run `npm run bootstrap` to leave one in build/nish",
    }
  }
  return resolveSeed(spec)
}

/** `--seed` and `--lines` take a value; everything else is a flag or a golden's name. */
const parse = (argv) => {
  const options = { update: false, verbose: false, lines: 10, seed: undefined, names: [] }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === "--update") {
      options.update = true
    } else if (arg === "--verbose") {
      options.verbose = true
    } else if (arg === "--seed") {
      options.seed = argv[++i]
    } else if (arg === "--lines") {
      options.lines = Number(argv[++i])
    } else {
      options.names.push(arg)
    }
  }
  return options
}

const main = (argv) => {
  const { update, verbose, lines, seed: given, names: named } = parse(argv)
  const limit = verbose ? Number.POSITIVE_INFINITY : lines
  const wanted = named.length > 0 ? GOLDEN_SET.filter((g) => named.includes(g.name)) : GOLDEN_SET
  if (wanted.length === 0) {
    process.stderr.write(
      `no such golden: ${named.join(" ")} (have ${GOLDEN_SET.map((g) => g.name).join(", ")})\n`
    )
    return 2
  }

  const seed = seedWithoutStage0(given)
  if (seed.error !== undefined) {
    process.stderr.write(`${seed.error}\n`)
    return 2
  }

  fs.mkdirSync(GOLDENS, { recursive: true })
  let failed = 0
  let bytes = 0
  let agreed = 0
  let shownFiles = 0
  const summary = []
  const fail = (file, report) => {
    failed++
    process.stdout.write(`  FAIL ${file}${report.length > 0 ? `: ${report[0]}` : ""}\n`)
    // A change to a checker rule can move the dump of hundreds of modules at
    // once; the first few files are what tells a reader what moved.
    if (shownFiles < FILES_SHOWN || verbose) {
      for (const line of report.slice(1)) {
        process.stdout.write(`${line}\n`)
      }
      shownFiles++
    }
  }
  for (const golden of wanted) {
    const produced = golden.produce(seed)
    if (produced.error !== undefined) {
      process.stdout.write(`  FAIL ${golden.name}: ${produced.error}\n`)
      failed++
      continue
    }
    for (const [file, text] of produced.files) {
      const at = goldenPath(file)
      bytes += Buffer.byteLength(text)
      if (update) {
        const before = fs.existsSync(at) ? fs.readFileSync(at, "utf8") : null
        if (before === text) {
          agreed++
          continue
        }
        fs.mkdirSync(path.dirname(at), { recursive: true })
        fs.writeFileSync(at, text)
        summary.push(`${file}: ${before === null ? "written" : "updated"}`)
        continue
      }
      if (!fs.existsSync(at)) {
        fail(file, ["missing (run with --update to write it)"])
        continue
      }
      const want = fs.readFileSync(at, "utf8")
      if (want === text) {
        agreed++
        continue
      }
      const d = diff(want, text, limit)
      const more =
        d.shown < d.total ? [`  ... and ${d.total - d.shown} more differing lines (--verbose for all)`] : []
      fail(file, [
        `${d.total} lines differ from what stage1 prints (${golden.oracle}'s coverage)`,
        ...d.out,
        ...more,
      ])
    }
    // A golden kept as a directory owns every file in it, so a file no program
    // produces any more is a module that left the corpus: `--update` removes
    // it, and the check fails on it rather than keep comparing nothing.
    if (produced.dir !== undefined) {
      for (const file of filesUnder(produced.dir)) {
        if (produced.files.has(file)) {
          continue
        }
        if (update) {
          fs.rmSync(goldenPath(file))
          summary.push(`${file}: removed`)
        } else {
          fail(file, ["no program loads this module any more (run with --update to remove it)"])
        }
      }
      if (update) {
        removeEmptyDirs(goldenPath(produced.dir))
      }
    }
    if (produced.note !== undefined && verbose) {
      process.stdout.write(`  ${golden.name}: ${produced.note}\n`)
    }
  }
  if (shownFiles < failed && !verbose) {
    process.stdout.write(
      `  (differences shown for the first ${FILES_SHOWN} failing files; --verbose for all)\n`
    )
  }
  // Under `--update` these are the only evidence that a regeneration did or
  // did not move anything, which is the question the person running it has.
  for (const line of summary) {
    process.stdout.write(`  ${line}\n`)
  }

  process.stdout.write(
    `${agreed + summary.length} golden files ${update ? `checked, ${summary.length} changed` : "agree"}, ${failed} failed, ${(bytes / 1024).toFixed(0)} KiB of goldens (seed ${seed.label})\n`
  )
  return failed === 0 ? 0 : 1
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)))
}
export { GOLDEN_SET, seedWithoutStage0 }
