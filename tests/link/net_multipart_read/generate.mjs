// Writes vectors.ts: multipart/form-data bodies as Node's FormData writes them
// (undici, the same encoder `fetch` uses), each beside the parts a reader must
// find in it, worked out here from the HTML form submission algorithm rather
// than read back from the body:
//
//   node tests/link/net_multipart_read/generate.mjs
//
// undici picks a random boundary, so a rerun rewrites every body; the parts
// stay the same.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const all = new Uint8Array(256)
for (let i = 0; i < 256; i++) all[i] = i
const enc = new TextEncoder()

// Each form is a list of [name, value, filename?, type?]; a value that is a
// Uint8Array is sent as a Blob, so it carries a filename and a Content-Type.
const FORMS = [
  [
    ["a", "hello"],
    ["empty", ""],
  ],
  [
    ["text", "line one\nline two\rline three\r\nend"],
    ["n\"a\r\nme", "v"],
  ],
  [
    ["upload", enc.encode("1,2\r\n3,4\r\n"), "data.csv", "text/csv"],
    ["note", "beside a file"],
  ],
  [["bytes", all, "all-bytes.bin", "application/octet-stream"]],
  [
    ["q", new Uint8Array([]), "a\"b\\c.txt", ""],
    ["blob", new Uint8Array([0x2d, 0x2d, 0x0d, 0x0a])],
  ],
  [["café", "naïve ☃"]],
]

/** The HTML algorithm's newline normalization: every CR, LF or CR LF becomes CR LF. */
const crlf = (s) => s.replace(/\r\n|\r|\n/g, "\r\n")
/** How a name or filename is escaped in a disposition: `"`, CR and LF percent-encoded. */
const escaped = (s) => crlf(s).replace(/"/g, "%22").replace(/\r/g, "%0D").replace(/\n/g, "%0A")
const hex = (bytes) => Buffer.from(bytes).toString("hex")
const quoted = (s) => JSON.stringify(s)

const out = [
  "// Generated by generate.mjs from Node's FormData; do not edit.",
  "",
  "/** A body as Node sends it and the parts a reader must find in it. */",
  "export class NodeVector {",
  "  /** The request's Content-Type. */",
  '  contentType: string = ""',
  "  /** The body, in hex. */",
  '  body: string = ""',
  "  /** Each part as `name|filename|type|data in hex`, `(none)` for no filename. */",
  "  parts: string[] = []",
  "}",
  "",
  "/** Every vector, in the order generate.mjs writes them. */",
  "export const nodeVectors = (): NodeVector[] => {",
  "  const vs: NodeVector[] = []",
]
for (const form of FORMS) {
  const fd = new FormData()
  const parts = []
  for (const [name, value, filename, type] of form) {
    if (value instanceof Uint8Array) {
      const blob = new Blob([value], type === undefined ? {} : { type })
      if (filename === undefined) fd.append(name, blob)
      else fd.append(name, blob, filename)
      const sent = type === undefined || type === "" ? "application/octet-stream" : type
      parts.push(`${escaped(name)}|${escaped(filename ?? "blob")}|${sent}|${hex(value)}`)
    } else {
      fd.append(name, value)
      parts.push(`${escaped(name)}|(none)|text/plain|${hex(enc.encode(crlf(value)))}`)
    }
  }
  const req = new Request("http://localhost/", { method: "POST", body: fd })
  const body = new Uint8Array(await req.arrayBuffer())
  out.push("  {")
  out.push("    const v: NodeVector = new NodeVector()")
  out.push(`    v.contentType = ${quoted(req.headers.get("content-type"))}`)
  out.push(`    v.body = ${quoted(hex(body))}`)
  for (const p of parts) out.push(`    v.parts.push(${quoted(p)})`)
  out.push("    vs.push(v)")
  out.push("  }")
}
out.push("  return vs", "}", "")
const here = path.dirname(fileURLToPath(import.meta.url))
fs.writeFileSync(path.join(here, "vectors.ts"), out.join("\n"))
