const classOf = (c: u8): u8 => CLASS[c]

export const main = (): void => {
  for (let row = 0; row < 16; row++) {
    const cells: string[] = []
    for (let col = 0; col < 16; col++) {
      cells.push(`${classOf(toU8(row * 16 + col))}`)
    }
    console.log(`${row * 16}: ${cells.join("")}`)
  }
}
