// hundred operands per function drawn across every reduction branch -- `tan`
// below pi/4, through Cody-Waite with none, one and both refinements, and through
// Payne-Hanek past 2^20 * pi/2; `atan2` in each of atan's intervals and every
// quadrant; `hypot` with a tiny second operand and through both rescales. Each
// `Want` is the correctly rounded result, and an answer passes when it is that
// double or a neighbour of it, which is what within one ulp of the exact value
// allows. The tables are `python3 bench/math-ulp/ulp.py --samples`.
