// `Math.tan`, `Math.atan2` and `Math.hypot` (`std/math.ts`) against mpmath: a few
// hundred operands per function drawn across every reduction branch -- `tan`
// below pi/4, through Cody-Waite with none, one and both refinements, and through
// Payne-Hanek past 2^20 * pi/2; `atan2` in each of atan's intervals and every
// quadrant, with a subnormal x and with both operands subnormal; `hypot` with a
// tiny second operand and through both rescales. Each `Want` is the correctly
// rounded result and each `Side` the side of it the exact value lies on (1 above,
// -1 below, 0 when `Want` is exact). An answer passes when it is `Want`, or the
// double next to `Want` on the exact value's side: the two doubles that bracket
// the exact value, which is all an error below one ulp allows. The tables are
// `python3 bench/math-ulp/ulp.py --samples`.

// Whether r is `want`, or the double next to it toward the exact value. A step of
// one in the bit pattern moves away from zero, so `side` turns into a step by
// `want`'s sign; a zero's neighbours are the smallest subnormals of either sign.
const near = (r: f64, want: f64, side: i32): boolean => {
  if (f64ToBits(r) === f64ToBits(want)) {
    return true;
  }
  if (want === 0.0) {
    return side > 0 ? r === 5e-324 : side < 0 && r === -5e-324;
  }
  const step: i32 = want < 0.0 ? -side : side;
  return side !== 0 && f64ToBits(r) === f64ToBits(want) + toI64(step);
};

