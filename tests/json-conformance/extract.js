/** test262's front matter: the `includes:` list and whether the file runs only in strict mode. */
const frontMatter = (source) => {
  const meta = /\/\*---([\s\S]*?)---\*\//.exec(source)?.[1] ?? ""
  const includes = []
  const inline = /^includes:\s*\[(.*)\]/m.exec(meta)
  if (inline !== null) {
    includes.push(
      ...inline[1]
        .split(",")
        .map((s) => s.trim())
        .filter((s) => s.length > 0)
    )
  } else {
    const block = /^includes:\s*\n((?:\s+-\s*.*\n)+)/m.exec(meta)
    for (const line of block?.[1].split("\n") ?? []) {
      const m = /-\s*(\S+)/.exec(line)
      if (m !== null) {
        includes.push(m[1])
      }
    }
  }
  const flags = /^flags:\s*\[(.*)\]/m.exec(meta)?.[1] ?? ""
  return {
    includes,
    strict: flags.includes("onlyStrict"),
    skip: /\b(raw|module|async)\b/.exec(flags)?.[1] ?? null,
  }
}

/** Runs one file in a child Node and answers what it recorded. */
const runOne = (testFile, harness, mode, nodeFlags) => {
  const run = spawnSync(
    process.execPath,
    [...nodeFlags, import.meta.filename, "--child", testFile, mode, ...harness],
    { encoding: "utf8", maxBuffer: 1 << 30 }
  )
  if (run.status !== 0) {
    return { error: `exit ${run.status}: ${run.stderr}`, cases: [], dropped: {} }
  }
  const at = run.stdout.lastIndexOf(MARKER)
  return at < 0
    ? { error: `no answer: ${run.stdout}`, cases: [], dropped: {} }
    : JSON.parse(run.stdout.slice(at + MARKER.length))
}

/** The `// Copyright` lines of an upstream file's header, comment marker dropped. */
const copyrightOf = (file) =>
  fs
    .readFileSync(file, "utf8")
    .split("\n")
    .filter((l) => /^\/\/ Copyright/.test(l))
    .map((l) => l.slice(3).trim())

const gitHead = (dir) =>
  spawnSync("git", ["-C", dir, "rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim()

/**
 * The data file for one upstream, as text: header, then one line per case.
 * Answers the text and the counts; `skipped` are the files not run, with the
 * flag that kept each out.
 */
const buildData = (upstream, commit, results, skipped) => {
  const lines = [
    ...NOTICES[upstream].map((l) => `# ${l}`),
    `# Upstream commit ${commit}, extracted by tests/json-conformance/extract.js, whose header gives the line format.`,
    ...skipped.map((s) => `# Not run, for its \`${s.flag}\` flag: ${s.name}`),
  ]
  const copyrights = [
    "# The copyright line of each upstream file the cases below come from, as its header states it:",
  ]
  const rows = []
  const totals = { cases: 0, files: 0, dropped: {}, failed: [], sources: [] }
  for (const { name, copyright, result } of results) {
    if (result.error !== null && result.error !== undefined) {
      totals.failed.push({ name, error: result.error.split("\n")[0] })
      lines.push(`# Not kept, it does not run to its end under Node: ${name}`)
      continue
    }
    totals.files++
    for (const [why, n] of Object.entries(result.dropped)) {
      totals.dropped[why] = (totals.dropped[why] ?? 0) + n
    }
    // A call the file makes twice with the same input is one case.
    const seen = new Set()
    let ordinal = 0
    for (const c of result.cases) {
      if (c.op === "parse") {
        c.expected = c.threw ? "throws" : parseExpected(c.text)
        if (c.expected.length > MAX_CASE_BYTES) {
          totals.dropped["too-long"] = (totals.dropped["too-long"] ?? 0) + 1
          continue
        }
      }
      const key = `${c.op} ${c.input}`
      if (seen.has(key)) {
        continue
      }
      seen.add(key)
      ordinal++
      rows.push(`${name}#${ordinal} ${c.op} ${c.expected} ${c.input}`)
      totals.cases++
    }
    if (ordinal > 0) {
      totals.sources.push(name)
      copyrights.push(...copyright.map((l) => `#   ${name}: ${l}`))
    }
  }
  return { totals, text: `${[...lines, ...copyrights, ...rows].join("\n")}\n` }
}

const report = (label, totals, skipped) => {
  process.stdout.write(`${label}: ${totals.cases} cases from ${totals.files} files\n`)
  for (const [why, n] of Object.entries(totals.dropped)) {
    process.stdout.write(`  dropped ${n}: ${DROPPED[why]}\n`)
  }
  for (const f of skipped) {
    process.stdout.write(`  not run, for its \`${f.flag}\` flag: ${f.name}\n`)
  }
  for (const f of totals.failed) {
    process.stdout.write(`  not kept, the file did not run to its end under Node: ${f.name}: ${f.error}\n`)
  }
}

const main = (argv) => {
  if (argv[0] === "--child") {
    child(argv[1], argv.slice(3), argv[2] === "strict", argv[2] === "d8")
    return 0
  }
  // JSON.stringify of a nesting 10,000 deep, which json-parser-recursive.js
  // parses, overflows Node's default stack; this one is four times as deep.
  if (!process.execArgv.some((a) => a.startsWith("--stack-size"))) {
    return (
      spawnSync(process.execPath, ["--stack-size=4000", import.meta.filename, ...argv], { stdio: "inherit" })
        .status ?? 1
    )
  }
  if (argv[0] === "--verify") {
    return verify()
  }
  if (argv.length !== 2) {
    process.stderr.write("usage: node tests/json-conformance/extract.js <test262 checkout> <V8 checkout>\n")
    return 2
  }
  const [test262, v8] = argv.map((d) => path.resolve(d))

  const t262Results = []
  const t262Skipped = []
  for (const dir of ["parse", "stringify"]) {
    const full = path.join(test262, "test", "built-ins", "JSON", dir)
    for (const entry of fs.readdirSync(full).sort()) {
      const testFile = path.join(full, entry)
      const meta = frontMatter(fs.readFileSync(testFile, "utf8"))
      if (meta.skip !== null) {
        t262Skipped.push({ name: `test262/${dir}/${entry}`, flag: meta.skip })
        continue
      }
      const harness = ["assert.js", "sta.js", ...meta.includes].map((h) => path.join(test262, "harness", h))
      t262Results.push({
        name: `test262/${dir}/${entry}`,
        copyright: copyrightOf(testFile),
        result: runOne(testFile, harness, meta.strict ? "strict" : "sloppy", []),
      })
    }
  }

  const v8Results = []
  const mjsunit = path.join(v8, "test", "mjsunit")
  for (const entry of fs.readdirSync(mjsunit).sort()) {
    if (entry.startsWith("json") && entry.endsWith(".js")) {
      const testFile = path.join(mjsunit, entry)
      const harness = [path.join(mjsunit, "mjsunit.js")]
      // The V8 flags the file asks d8 for, which Node hands to V8 as they are.
      const flags =
        /^\/\/ Flags:(.*)$/m.exec(fs.readFileSync(testFile, "utf8"))?.[1].trim().split(/\s+/) ?? []
      v8Results.push({
        name: `v8/${entry}`,
        copyright: copyrightOf(testFile),
        result: runOne(testFile, harness, "d8", flags),
      })
    }
  }

  const t262 = buildData("test262", gitHead(test262), t262Results, t262Skipped)
  const v8Data = buildData("v8", gitHead(v8), v8Results, [])
  report("test262", t262.totals, t262Skipped)
  report("v8", v8Data.totals, [])
  // Nothing is written unless the files that did not run are exactly the ones
  // the header names, and the generated loop was every code unit.
  const failed = [...t262.totals.failed, ...v8Data.totals.failed].map((f) => f.name).sort()
  const generated = v8Data.totals.dropped.generated ?? 0
  const sources = [...t262.totals.sources, ...v8Data.totals.sources].sort()
  const skipped = t262Skipped.map((f) => f.name).sort()
  if (
    failed.join(" ") !== [...NOT_RUN_UNDER_NODE].sort().join(" ") ||
    generated !== GENERATED.count ||
    sources.join(" ") !== [...SOURCE_FILES].sort().join(" ") ||
    skipped.join(" ") !== [...NOT_RUN_FOR_FLAG].sort().join(" ")
  ) {
    process.stderr.write(
      `extract.js: wrote nothing: the files that did not run are ${failed.join(", ") || "none"} (want ${NOT_RUN_UNDER_NODE.join(", ")}); those not run for a flag are ${skipped.join(", ") || "none"} (want ${NOT_RUN_FOR_FLAG.join(", ") || "none"}); the generated loop made ${generated} calls (want ${GENERATED.count}); the cases come from ${sources.length} files (want the ${SOURCE_FILES.length} SOURCE_FILES names)\n`
    )
    return 1
  }
  fs.writeFileSync(path.join(HERE, "test262.txt"), t262.text)
  fs.writeFileSync(path.join(HERE, "v8.txt"), v8Data.text)
  return 0
}

process.exitCode = main(process.argv.slice(2))
