/** One byte array in the packed spelling. */
const pack = (bytes) => {
  let out = ""
  for (const b of bytes) {
    out +=
      b > 0x20 && b < 0x7f && b !== 0x25
        ? String.fromCharCode(b)
        : `%${b.toString(16).toUpperCase().padStart(2, "0")}`
  }
  return out
}

/** A JavaScript string's UTF-8, with a lone surrogate as its three WTF-8 bytes. */
const wtf8 = (s) => {
  const out = []
  for (let i = 0; i < s.length; i++) {
    let c = s.charCodeAt(i)
    if (c >= 0xd800 && c <= 0xdbff && i + 1 < s.length) {
      const d = s.charCodeAt(i + 1)
      if (d >= 0xdc00 && d <= 0xdfff) {
        c = 0x10000 + ((c - 0xd800) << 10) + (d - 0xdc00)
        i++
      }
    }
    if (c < 0x80) {
      out.push(c)
    } else if (c < 0x800) {
      out.push(0xc0 | (c >> 6), 0x80 | (c & 63))
    } else if (c < 0x10000) {
      out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63))
    } else {
      out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63))
    }
  }
  return out
}

/** A string as a word's JSON literal: printable ASCII as itself, every other unit and `"`, `\`, `%` as `\u`. */
const literal = (s) => {
  let out = '"'
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i)
    out +=
      c > 0x20 && c < 0x7f && c !== 0x22 && c !== 0x5c && c !== 0x25
        ? s[i]
        : `\\u${c.toString(16).padStart(4, "0")}`
  }
  return `${out}"`
}

/** A number as its word's text: 17 significant digits, which name the double exactly. */
const numberText = (x) => {
  if (Object.is(x, -0)) {
    return "-0"
  }
  return Number.isFinite(x) ? x.toPrecision(17) : String(x)
}

/** What `words` answers for a value past `MAX_CASE_BYTES`, found before the words are all built. */
const TOO_LONG = Symbol("too long")
/** What a stringify call records when even walking its value throws. */
const THROWS = Symbol("throws")

/** `value` as words, `null` when it is not plain data, or `TOO_LONG`. */
const words = (value) => {
  const out = []
  const open = new Set()
  let size = 0
  let tooLong = false
  const walk = (v) => {
    size += typeof v === "string" ? v.length : 1
    if (size > MAX_CASE_BYTES) {
      tooLong = true
      return false
    }
    if (v === null) {
      out.push("z")
      return true
    }
    switch (typeof v) {
      case "boolean":
        out.push(v ? "t" : "f")
        return true
      case "number":
        out.push(`n:${numberText(v)}`)
        return true
      case "string":
        out.push(`s:${literal(v)}`)
        return true
      case "object":
        break
      default:
        return false
    }
    if (open.has(v) || Object.getOwnPropertySymbols(v).length > 0) {
      return false
    }
    open.add(v)
    let ok = true
    if (Array.isArray(v)) {
      const names = Object.getOwnPropertyNames(v)
      ok =
        Object.getPrototypeOf(v) === Array.prototype &&
        !("toJSON" in v) &&
        names.length === v.length + 1 &&
        names.every((name) => {
          const d = Object.getOwnPropertyDescriptor(v, name)
          return name === "length" || (d.enumerable && "value" in d && String(Number(name)) === name)
        })
      out.push("[")
      for (let i = 0; ok && i < v.length; i++) {
        ok = walk(v[i])
      }
      out.push("]")
    } else {
      const names = Object.getOwnPropertyNames(v)
      ok =
        Object.getPrototypeOf(v) === Object.prototype &&
        !("toJSON" in v) &&
        names.every((name) => {
          const d = Object.getOwnPropertyDescriptor(v, name)
          return d.enumerable && "value" in d
        })
      out.push("{")
      for (const name of ok ? Object.keys(v) : []) {
        out.push(`k:${literal(name)}`)
        if (!walk(v[name])) {
          ok = false
          break
        }
      }
      out.push("}")
    }
    open.delete(v)
    return ok
  }
  const ok = walk(value)
  if (tooLong) {
    return TOO_LONG
  }
  return ok ? out.join(" ") : null
}

/** The gap `JSON.stringify` builds from a number or string space, or `null` for a space of another type. */
const gapOf = (space) => {
  if (space === undefined) {
    return ""
  }
  if (typeof space === "number") {
    const n = Math.min(10, Math.trunc(space))
    return n >= 1 ? " ".repeat(n) : ""
  }
  return typeof space === "string" ? space.slice(0, 10) : null
}

/** Runs `testFile` after `harness` in this process, recording the calls it makes itself; prints the result as JSON. */
const child = (testFile, harness, strict, d8) => {
  const realParse = JSON.parse
  const realStringify = JSON.stringify
  const cases = []
  const dropped = {}
  const drop = (why) => {
    dropped[why] = (dropped[why] ?? 0) + 1
  }
  // A call is the test's when the frame that made it is in the test file, or in
  // code the harness evaluated from a string the test handed it.
  const frameOfCall = () => (new Error("where JSON was called from").stack ?? "").split("\n")[3] ?? ""
  const fromTest = (frame) =>
    frame.includes(testFile) || /\(eval at [^)]*\), <anonymous>:\d+:\d+\)$/.test(frame)
  // The line of the call `GENERATED` names, when this file holds it.
  const sourceLines = fs.readFileSync(testFile, "utf8").split("\n")
  const generatedLine =
    path.basename(testFile) === GENERATED.file
      ? sourceLines.findIndex((l) => l.trim() === GENERATED.call) + 1
      : 0
  const keep = (row) => {
    if (row.input.length > MAX_CASE_BYTES || row.expected.length > MAX_CASE_BYTES) {
      drop("too-long")
    } else {
      cases.push(row)
    }
  }
  // Methods rather than functions, so that each wrapper is, like the original,
  // not a constructor and has no prototype: test262's builtin.js checks both.
  const wrappers = {
    parse(text, reviver) {
      if (!fromTest(frameOfCall())) {
        return realParse.call(this, text, reviver)
      }
      if (reviver !== undefined) {
        drop("reviver")
      } else if (typeof text !== "string") {
        drop("parse-non-string")
      } else {
        // What the value writes back is worked out by the parent, whose stack is
        // the default one: json-parser-recursive.js parses a nesting 10,000 deep
        // under --stack-size=100, which JSON.parse survives and JSON.stringify
        // would not.
        let threw = null
        let result
        try {
          result = realParse(text)
        } catch (e) {
          threw = e
        }
        if (threw === null || threw instanceof SyntaxError) {
          keep({ op: "parse", threw: threw !== null, text, input: pack(wtf8(text)), expected: "" })
        } else {
          drop("throws")
        }
        if (threw !== null) {
          throw threw
        }
        return result
      }
      return realParse.call(this, text, reviver)
    },
    stringify(value, replacer, space) {
      const frame = frameOfCall()
      if (!fromTest(frame)) {
        return realStringify.call(this, value, replacer, space)
      }
      if (generatedLine > 0 && frame.includes(`${testFile}:${generatedLine}:`)) {
        drop("generated")
        return realStringify.call(this, value, replacer, space)
      }
      const gap = gapOf(space)
      let input = null
      try {
        input = replacer === undefined || replacer === null ? words(value) : null
      } catch (e) {
        // The walk overflows the stack on json-stringify-recursive.js's nesting
        // 10,000 deep, as JSON.stringify does under its --stack-size=100; any
        // other throw is a Proxy's trap, which is the object model.
        input = e instanceof RangeError ? THROWS : null
      }
      if (replacer !== undefined && replacer !== null) {
        drop("replacer")
      } else if (gap === null) {
        drop("space-object")
      } else if (input === THROWS) {
        drop("throws")
      } else if (input === TOO_LONG) {
        drop("too-long")
      } else if (input === null) {
        drop("not-plain")
      } else {
        // Plain data runs no code and answers a string, but V8 still throws a
        // RangeError for a nesting past its stack (json-stringify-recursive.js).
        let answer = ""
        try {
          answer = realStringify(value, null, space)
        } catch (e) {
          drop("throws")
          throw e
        }
        keep({
          op: gap === "" ? "stringify" : `indent:${pack(Buffer.from(gap, "utf8"))}`,
          expected: pack(Buffer.from(answer, "utf8")),
          input,
        })
        return answer
      }
      return realStringify.call(this, value, replacer, space)
    },
  }
  JSON.parse = wrappers.parse
  JSON.stringify = wrappers.stringify
  // A V8 test patches the prototypes (json-stringify-stack.js puts a throwing
  // setter on Object.prototype), so what it adds is taken off again before this
  // script writes its answer. And d8's global object has no `global`, the
  // cycle JSON.stringify(this) in json2.js would otherwise trip over.
  const protos = [Object.prototype, Array.prototype]
  const before = protos.map((p) => new Set(Reflect.ownKeys(p)))
  if (d8) {
    delete globalThis.global
  }
  let error = null
  try {
    for (const file of harness) {
      vm.runInThisContext(fs.readFileSync(file, "utf8"), { filename: file })
    }
    const source = fs.readFileSync(testFile, "utf8")
    vm.runInThisContext(strict ? `"use strict";\n${source}` : source, { filename: testFile })
  } catch (e) {
    error = String(e?.stack ?? e)
  }
  JSON.parse = realParse
  JSON.stringify = realStringify
  protos.forEach((p, i) => {
    for (const key of Reflect.ownKeys(p)) {
      if (!before[i].has(key)) {
        Reflect.deleteProperty(p, key)
      }
    }
  })
  // After a marker, because a test may print to stdout itself.
  process.stdout.write(`${MARKER}${realStringify({ error, cases, dropped })}`)
}

/** A parse case's `expected` for a text that parses: `-0`, or what its value writes back, packed. */
const parseExpected = (text) => {
  const value = JSON.parse(text)
  return Object.is(value, -0) ? "-0" : pack(Buffer.from(JSON.stringify(value), "utf8"))
}

// ---- Reading a data file back, for --verify -----------------------------------

/** The bytes of a packed field. */
const unpack = (packed) =>
  Buffer.from(
    packed.replace(/%([0-9A-F]{2})/g, (_, h) => String.fromCharCode(Number.parseInt(h, 16))),
    "latin1"
  )

/** `wtf8`'s inverse: a surrogate's three bytes come back as that lone unit. */
const fromWtf8 = (bytes) => {
  let out = ""
  let i = 0
  while (i < bytes.length) {
    const b = bytes[i]
    let n = 4
    if (b < 0x80) {
      n = 1
    } else if (b < 0xe0) {
      n = 2
    } else if (b < 0xf0) {
      n = 3
    }
    let c = n === 1 ? b : b & (0xff >> (n + 1))
    for (let k = 1; k < n; k++) {
      c = (c << 6) | (bytes[i + k] & 63)
    }
    out += String.fromCodePoint(c)
    i += n
  }
  return out
}

/** A stringify case's words back into the value they spell. */
const valueFromWords = (input) => {
  const ws = input.split(" ")
  let at = 0
  const value = () => {
    const w = ws[at++]
    if (w === "[") {
      const a = []
      while (ws[at] !== "]") {
        a.push(value())
      }
      at++
      return a
    }
    if (w === "{") {
      const o = {}
      while (ws[at] !== "}") {
        // Defined rather than assigned, so that a key `__proto__` is a property.
        const key = JSON.parse(ws[at++].slice(2))
        Object.defineProperty(o, key, {
          value: value(),
          enumerable: true,
          writable: true,
          configurable: true,
        })
      }
      at++
      return o
    }
    if (w.startsWith("s:")) {
      return JSON.parse(w.slice(2))
    }
    if (w.startsWith("n:")) {
      return w === "n:-0" ? -0 : Number(w.slice(2))
    }
    return w === "z" ? null : w === "t"
  }
  return value()
}

/** One line's `expected`, worked out again from its op and input. */
const expectedOf = (op, input) => {
  if (op === "parse") {
    const text = fromWtf8(unpack(input))
    try {
      return parseExpected(text)
    } catch {
      return "throws"
    }
  }
  const gap = op.startsWith("indent:") ? unpack(op.slice(7)).toString("utf8") : ""
  return pack(Buffer.from(JSON.stringify(valueFromWords(input), null, gap), "utf8"))
}

/**
 * `--verify`: every line of both data files, its expected value worked out
 * again with this Node's JSON. A line edited by hand, or a JSON that answers
 * differently, is named. Answers the exit status.
 */
const verify = () => {
  const problems = []
  const names = new Set()
  const notKept = []
  const notRun = []
  const sources = []
  let count = 0
  for (const file of ["test262.txt", "v8.txt"]) {
    // The files the header gives a copyright line for, and the files the cases name: one set.
    const listed = new Set()
    const named = new Set()
    for (const line of fs.readFileSync(path.join(HERE, file), "utf8").split("\n")) {
      const copyright = /^# {3}(\S+): Copyright/.exec(line)
      if (copyright !== null) {
        listed.add(copyright[1])
      }
      const flagged = /^# Not run, for its `\w+` flag: (\S+)$/.exec(line)
      if (flagged !== null) {
        notRun.push(flagged[1])
      }
      const missing = /^# Not kept, it does not run to its end under Node: (\S+)$/.exec(line)
      if (missing !== null) {
        notKept.push(missing[1])
      }
      if (line.length === 0 || line.startsWith("#")) {
        continue
      }
      named.add(line.slice(0, line.indexOf("#")))
      const [name, op, expected] = line.split(" ", 3)
      const input = line.slice(name.length + op.length + expected.length + 3)
      count++
      if (names.has(name)) {
        problems.push(`${name}: named twice`)
      }
      names.add(name)
      const again = expectedOf(op, input)
      if (again !== expected) {
        problems.push(`${name}: the file says ${expected.slice(0, 80)}, Node says ${again.slice(0, 80)}`)
      }
    }
    sources.push(...listed)
    if ([...listed].sort().join(" ") !== [...named].sort().join(" ")) {
      problems.push(
        `${file}: its header lists ${[...listed].join(", ")}, its cases come from ${[...named].join(", ")}`
      )
    }
  }
  if (sources.sort().join(" ") !== [...SOURCE_FILES].sort().join(" ")) {
    problems.push(
      `the cases come from ${sources.join(", ")}, not the ${SOURCE_FILES.length} files SOURCE_FILES names`
    )
  }
  if (notRun.sort().join(" ") !== [...NOT_RUN_FOR_FLAG].sort().join(" ")) {
    problems.push(
      `the headers say ${notRun.join(", ")} were not run for a flag, not ${NOT_RUN_FOR_FLAG.join(", ") || "none"}`
    )
  }
  if (notKept.sort().join(" ") !== [...NOT_RUN_UNDER_NODE].sort().join(" ")) {
    problems.push(
      `the headers say ${notKept.join(", ") || "nothing"} did not run, not ${NOT_RUN_UNDER_NODE.join(", ")}`
    )
  }
  process.stdout.write(`${count} cases, ${problems.length} that Node does not reproduce\n`)
  for (const p of problems) {
    process.stdout.write(`  ${p}\n`)
  }
  return count > 0 && problems.length === 0 ? 0 : 1
}

