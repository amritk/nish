// Extracts the JSON.parse and JSON.stringify cases of test262 and V8 into the
// data files beside this script, `test262.txt` and `v8.txt`, which
// `tests/link/std_json_conformance` runs through nish/json-tokenizer and
// JsonWriter.
//
//   node tests/json-conformance/extract.js <test262 checkout> <V8 checkout>
//   node tests/json-conformance/extract.js --verify
//
// Each upstream file runs under Node with its own harness (test262's
// `harness/assert.js`, `sta.js` and the `includes:` its front matter names;
// V8's `test/mjsunit/mjsunit.js`, with the V8 flags its `// Flags:` line
// asks for), with `JSON.parse` and `JSON.stringify` wrapped so that every call
// the test file itself makes is recorded with what it answered. A file is kept
// only when it runs to its end, every assertion passing, so a recorded answer
// is the one the upstream assertion requires. Three do not run under Node, and
// each holds only calls the rules below drop: test262's
// `replacer-array-proxy-revoked-realm.js` and `value-bigint-cross-realm.js`
// need a second realm (`$262`), and V8's `json-stringify-stack.js` leaves a
// throwing setter on `Object.prototype` that Node itself then trips over.
// The script writes nothing, and exits 1, unless the files that do not run are
// exactly those three (`NOT_RUN_UNDER_NODE`); a file test262 marks `raw`,
// `module` or `async` is not run, and is named on stdout and in the header.
// A call is a case when it is about JSON text rather than JavaScript's object
// model:
//
// - `JSON.parse(text)` with a string and no reviver;
// - `JSON.stringify(value)`, or with a `null` replacer and a number or string
//   space, where `value` is plain data: null, a boolean, a number, a string, and
//   arrays (dense, no extra properties) and objects (the plain prototype, only
//   enumerable data properties with string keys, no `toJSON`) of those, with no
//   cycle.
//
// Everything else is dropped, and each dropped kind is listed in `DROPPED`
// below and counted when the script runs: reviver, replacer, toJSON,
// space-as-object, Proxy, getters, the BigInt TypeError, and the rest of the
// object model. The calls of V8 json.js's loop over every UTF-16 code unit
// (`GENERATED`) are generated by tests/run.js rather than kept. A call a file
// makes twice with the same input is one case. The
// data files are Node's answers, so `--verify`, which `tests/run.js` runs,
// works every expected value out again with Node's own JSON and fails on a line
// it does not reproduce, on a header whose list of files differs from the files
// the cases name, or on a header whose not-kept files are not those three.
// Each data file's header carries the upstream notice, the commit, and the
// copyright line of every file its cases come from.
//
// A line is `<name> <op> <expected> <input>`:
//
// - `name` is the upstream file and the case's ordinal within it, so that
//   `divergences.txt` can name it.
// - `op` is `parse`, `stringify`, or `indent:<gap>` for a stringify whose space
//   makes a non-empty gap (the gap packed).
// - For `parse`, `input` is the text, packed: its UTF-8, with every byte
//   outside `!` to `~`, and every `%`, written as `%XX`, as
//   `tests/json-suite/pack.js` writes JSONTestSuite. A lone surrogate is
//   written as its three WTF-8 bytes. `expected` is `throws`, `-0` for a
//   negative zero, or `JSON.stringify` of the value, packed.
// - For `stringify`, `input` is the value as words, one per token: `[ ] { }`,
//   `t f z` for true, false and null, `n:` and the number to 17 significant
//   digits (or `NaN`, `Infinity`, `-Infinity`, `-0`), and `s:` and `k:` and a
//   JSON string literal in which every UTF-16 unit outside `!` to `~`, and
//   every `"`, `\` and `%`, is a `\u` escape. `expected` is what
//   `JSON.stringify` answered, packed.
