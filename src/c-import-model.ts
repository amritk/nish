// The data model a module `nish c-import` writes records in its header
// comment, and the refusal a build for the other model gives it (D3). It is
// apart from `src/c-import.ts` so that `src/compilation.ts`, which reads every
// module's first lines, does not import the generator.

/** The first words of every module `nish c-import` writes. */
export const C_IMPORT_MARKER: string = "// Generated by nish c-import"

/** The header-comment line that records the data model. */
export const DATA_MODEL_LINE: string = "// Data model: "

/**
 * The data model of a triple: `ILP32` for wasm32, where `long` and a pointer
 * are 32 bits, and `LP64` for every other target the compiler has.
 *
 * @param triple a canonical target triple.
 * @returns `ILP32` or `LP64`.
 */
export const dataModelOf = (triple: string): string => (triple.startsWith("wasm32") ? "ILP32" : "LP64")

/** Why a build refuses a generated module (D3): the span and the message. */
export class DataModelRefusal {
  start: i32 = 0
  end: i32 = 0
  message: string = ""
}

/**
 * The refusal of a module `nish c-import` wrote for another data model than
 * the build's, or null when the text is no such module or the models agree.
 * A wasm build is ILP32 and every other target nish builds is LP64, so a
 * `long` or a pointer-sized field a module declares has the size the build
 * gives it only when the two agree.
 *
 * @param text the module's source.
 * @param wasm whether the build targets wasm.
 * @returns the span of the recorded model and the message, or null.
 */
export const dataModelRefusal = (text: string, wasm: boolean): DataModelRefusal | null => {
  if (!text.startsWith(C_IMPORT_MARKER)) {
    return null
  }
  const at = text.indexOf(`\n${DATA_MODEL_LINE}`)
  if (at < 0) {
    return null
  }
  const from = at + 1 + DATA_MODEL_LINE.length
  let end = text.indexOf("\n", from)
  if (end < 0) {
    end = text.length
  }
  // A module checked out with CRLF line ends records the same model.
  if (end > from && text.charCodeAt(end - 1) === 13) {
    end = end - 1
  }
  const recorded = text.slice(from, end)
  const model = wasm ? "ILP32" : "LP64"
  if (recorded === model) {
    return null
  }
  const refusal = new DataModelRefusal()
  refusal.start = from
  refusal.end = end
  refusal.message = `this module was written by nish c-import for ${recorded}, and this build is ${model}: a C type's size differs between the two data models, so regenerate the module with \`nish c-import --target\` for this build`
  return refusal
}
